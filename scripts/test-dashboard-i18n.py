#!/usr/bin/env python

"""Smoke-test the dashboard i18n engine (FR -> EN) with Node.js.

Extracts the i18n block from the generated dashboard, stubs a minimal DOM and
asserts that a representative sample of French strings is translated.

Usage::

    python scripts/test-dashboard-i18n.py [dashboard/index.html]
"""

from __future__ import annotations

import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent

STUB = """
globalThis.window = globalThis;
globalThis.addEventListener = () => {};
globalThis.Node = { TEXT_NODE: 3, ELEMENT_NODE: 1, DOCUMENT_NODE: 9 };
globalThis.NodeFilter = { SHOW_TEXT: 4, SHOW_ELEMENT: 1, FILTER_ACCEPT: 1, FILTER_REJECT: 2 };
globalThis.localStorage = { getItem: () => null, setItem: () => {} };
globalThis.location = { search: '' };
globalThis.MutationObserver = class { observe() {} };
globalThis.CustomEvent = class { constructor(n, o) { this.type = n; Object.assign(this, o); } };
globalThis.document = {
  documentElement: { lang: 'fr', nodeType: 1, tagName: 'HTML' },
  addEventListener: () => {},
  querySelectorAll: () => [],
  dispatchEvent: () => {},
  createTreeWalker: () => ({ nextNode: () => null }),
};
"""

# (input, expected output) — expected === null means "must change"
CASES = [
    ("\U0001F4CB Détail par règle API Green Score", "\U0001F4CB Breakdown by API Green Score rule"),
    ("\U0001F511 Métriques clés", "\U0001F511 Key metrics"),
    ("Chargez un rapport JSON généré par", "Load a JSON report generated by"),
    ("\U0001F1E9\U0001F1EA Allemagne — 385 gCO₂/kWh", "\U0001F1E9\U0001F1EA Germany — 385 gCO₂/kWh"),
    ("\U0001F1EB\U0001F1F7 France — 53 gCO₂/kWh", "\U0001F1EB\U0001F1F7 France — 53 gCO₂/kWh"),
    ("Règle", "Rule"),
    ("Règles écodesign violées", "Eco-design rules violated"),
    ("\U0001F4E6 Transfert total", "\U0001F4E6 Total transfer"),
    ("Score actuel : 45/100", "Current score: 45/100"),
    ("\u26A1 Énergie / appel : 0.0042 Wh", "\u26A1 Energy / call: 0.0042 Wh"),
    ("\U0001F7E2 Électricité très décarbonée", "\U0001F7E2 Very low-carbon electricity"),
    ("Erreur: ", "Error: "),
    ("Aucun fichier impacté", "No impacted file"),
    ("\u2705 Aucun fichier impacté", "\u2705 No impacted file"),
    ("DE08 — Filtrage de champs", "DE08 — Field filtering"),
    ("Devoxx France 2026 — Tools in Action", "Devoxx France 2026 — Tools in Action"),
    ("10 000 req/jour × 365 jours/an", "10 000 req/day × 365 days/year"),
]


def main() -> int:
    target = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "dashboard" / "index.html"
    html = target.read_text(encoding="utf-8")
    try:
        block = html.split("<!-- I18N:BEGIN -->")[1].split("<!-- I18N:END -->")[0]
        js = block.split("<script>")[1].split("</script>")[0]
    except IndexError:
        print(f"✗ no i18n block found in {target}", file=sys.stderr)
        return 1

    cases_js = ",\n".join(
        "  [%s, %s]" % (_js_str(src), _js_str(exp)) for src, exp in CASES
    )
    tail = f"""
const I = globalThis.I18N;
I.lang = 'en';
const CASES = [
{cases_js}
];
let failed = 0;
for (const [src, exp] of CASES) {{
    const got = I.t(src);
    const ok = got === exp;
    if (!ok) failed++;
    console.log((ok ? 'PASS' : 'FAIL') + '  ' + JSON.stringify(src) + ' -> ' + JSON.stringify(got));
    if (!ok) console.log('      expected ' + JSON.stringify(exp));
}}
I.lang = 'fr';
const passthrough = I.t({_js_str("\U0001F511 Métriques clés")});
if (passthrough !== {_js_str("\U0001F511 Métriques clés")}) {{
    failed++; console.log('FAIL  French passthrough altered: ' + JSON.stringify(passthrough));
}} else {{
    console.log('PASS  French passthrough untouched');
}}
console.log(failed === 0 ? '\\nAll i18n checks passed' : `\\n${{failed}} i18n check(s) failed`);
process.exit(failed === 0 ? 0 : 1);
"""

    tmp = pathlib.Path(tempfile.gettempdir()) / "green-dashboard-i18n-test.mjs"
    tmp.write_text(STUB + js + tail, encoding="utf-8")
    proc = subprocess.run(["node", str(tmp)], capture_output=True, text=True, encoding="utf-8")
    print(proc.stdout)
    if proc.stderr.strip():
        print(proc.stderr, file=sys.stderr)
    return proc.returncode


def _js_str(s: str) -> str:
    import json
    return json.dumps(s, ensure_ascii=False)


if __name__ == "__main__":
    raise SystemExit(main())

